import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

/** Build only B0-A data; never activate the older generic router's 410 rules. */
export async function getRoutingPaths(root, routes) {
  const validPaths = routes.map(route => route.path).sort();
  const valid = new Set(validPaths);
  const localized = JSON.parse(await readFile(path.join(root, 'src/i18n/arabic-route-fallbacks.json'), 'utf8'));
  for (const [source, destination] of Object.entries(localized)) {
    if (valid.has(source) || !valid.has(source.slice(3)) || !valid.has(destination)) throw new Error(`Invalid Arabic fallback: ${source} -> ${destination}`);
  }
  const app = await readFile(path.join(root, 'src/App.tsx'), 'utf8');
  const service = await readFile(path.join(root, 'src/pages/ServicePage.tsx'), 'utf8');
  const legacy = new Set();
  for (const match of app.matchAll(/<Route\s+path="([^"]+)"\s+element=\{<(?:Navigate|PreserveQueryNavigate)\s+to="([^"]+)"/g)) {
    if (!/[:*]/.test(match[1])) legacy.add(match[1]);
  }
  const servicePairs = app.match(/const mercedesBrandServiceRedirects[^=]*=\s*\[([\s\S]*?)\n\];/)?.[1];
  if (!servicePairs) throw new Error('Missing existing Mercedes service redirects');
  for (const match of servicePairs.matchAll(/\["([^"]+)"/g)) legacy.add(`/brands/mercedes-benz-service-dubai/${match[1]}`);
  for (const name of ['OLD_TO_NEW_SLUG', 'EXTERNAL_REDIRECTS']) {
    const block = service.match(new RegExp(`const ${name}[^=]*=\\s*\\{([\\s\\S]*?)\\n\\};`))?.[1];
    if (!block) throw new Error(`Missing existing service redirects: ${name}`);
    for (const match of block.matchAll(/'([^']+)'\s*:/g)) legacy.add(`/services/${match[1]}`);
  }
  for (const source of [...legacy]) if (!source.startsWith('/ar/')) legacy.add(`/ar${source}`);
  return { validPaths, legacyPaths: [...legacy].sort(), localizedFallbacks: Object.entries(localized) };
}

export async function writeRoutingResponseData(root, routes, notFoundHtml) {
  const paths = await getRoutingPaths(root, routes);
  const client = JSON.parse(await readFile(path.join(root, 'src/lib/routing-paths.json'), 'utf8'));
  if (JSON.stringify(client) !== JSON.stringify({ validPaths: paths.validPaths, legacyPaths: paths.legacyPaths })) throw new Error('Client routing paths are stale; run the build pipeline with sync-routing-paths.mjs before the client build.');
  const data = { ...paths, notFoundHtml };
  const output = '// Generated by scripts/prerender.mjs. Rebuild before reviewing or releasing.\n' + Object.entries(data).map(([key, value]) => `export const ${key} = ${JSON.stringify(value)};`).join('\n') + '\n';
  await writeFile(path.join(root, 'cloudflare/routing-response-data.js'), output);
}
