import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const directory = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(directory, '../../..');
const candidate = JSON.parse(await readFile(path.join(root, 'outputs/mercedes-oil-routing-2026-10-21/proposal/single-redirect-rule.json'), 'utf8'));
const snapshot = await readFile(path.resolve(directory, '../cloudflare/pre-deploy-form.txt'), 'utf8');
assert.ok(snapshot.includes('- heading "Create new Single Redirect" [level=1]'));
assert.ok(!snapshot.includes('- heading "Edit Single Redirect" [level=1]'));
assert.ok(snapshot.includes(`- textbox "Rule name (required)": ${candidate.description}`));
const line = snapshot.split(/\r?\n/).find(l => l.includes(': "(http.host in '));
assert.ok(line);
assert.equal(JSON.parse(line.slice(line.indexOf(': "(http.host in ') + 2)), candidate.expression);
assert.ok(snapshot.includes(`- textbox "URL": ${candidate.action_parameters.from_value.target_url.value}`));
assert.ok(snapshot.includes('- generic: Static'));
assert.ok(snapshot.includes('- generic: "308 - Advanced: Permanent, HTTP method preserved"'));
assert.ok(snapshot.includes('- checkbox "Preserve query string" [checked]'));
assert.ok(snapshot.includes('- generic: First'));
assert.ok(snapshot.includes('- generic: Rule validation passed'));
assert.ok(snapshot.includes('- button "Deploy":'));
const report = { reviewedAt: new Date().toISOString(), passed: true, createOneForm: true, expressionExactlyMatchesCandidate: true, targetExactlyMatchesCandidate: true, status308: true, queryPreservationChecked: true, firstPosition: true, serverUiValidationPassed: true, deployNotYetClickedAtCapture: true, snapshot: '../cloudflare/pre-deploy-form.txt', limitation: 'Visible pre-submission form review only; does not establish completed activation or post-activation HTTP behavior.' };
await writeFile(path.join(directory, 'create-form-review.json'), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report));
