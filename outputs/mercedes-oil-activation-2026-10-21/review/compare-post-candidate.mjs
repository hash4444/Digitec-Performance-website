import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const directory = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(directory, '../../..');
const folder = path.resolve(directory, '../cloudflare');
const candidate = JSON.parse(await readFile(path.join(root, 'outputs/mercedes-oil-routing-2026-10-21/proposal/single-redirect-rule.json'), 'utf8'));
const recorded = JSON.parse(await readFile(path.join(folder, 'new-rule.json'), 'utf8'));
const snapshot = await readFile(path.join(folder, 'post-new-rule.txt'), 'utf8');
const overview = await readFile(path.join(folder, 'post-rules-overview.txt'), 'utf8');
const inventory = await readFile(path.join(folder, 'post-rule-inventory.txt'), 'utf8');
assert.deepEqual(recorded.scope, candidate);
assert.equal(recorded.ruleId, '5addb0c068414fb5b985a869ded26c68');
assert.ok(recorded.enabled && recorded.observedFirst);
assert.ok(snapshot.includes('- heading "Edit Single Redirect" [level=1]'));
assert.ok(snapshot.includes(`- textbox "Rule name (required)": ${candidate.description}`));
const line = snapshot.split(/\r?\n/).find(l => l.includes(': "(http.host in '));
assert.ok(line);
assert.equal(JSON.parse(line.slice(line.indexOf(': "(http.host in ') + 2)), candidate.expression);
assert.ok(snapshot.includes(`- textbox "URL": ${candidate.action_parameters.from_value.target_url.value}`));
assert.ok(snapshot.includes('- generic: Static'));
assert.ok(snapshot.includes('- generic: "308 - Advanced: Permanent, HTTP method preserved"'));
assert.ok(snapshot.includes('- checkbox "Preserve query string" [checked]'));
assert.ok(snapshot.includes('- generic: First'));
assert.ok(inventory.includes('- paragraph: 3 out of 10'));
assert.equal((inventory.match(/- checkbox \[checked\]/g) || []).length, 3);
assert.ok(overview.includes(`/rules/redirect-rules/${recorded.ruleId}`));
assert.ok(overview.includes('row "Drag row 1 Mercedes oil change legacy URLs to existing service'));
assert.ok(overview.includes('308 redirect to https://digitecme.com/services/mercedes-oil-change-dubai Active Menu'));
const originalComparison = JSON.parse(await readFile(path.join(directory, 'post-cloudflare-comparison.json'), 'utf8'));
assert.ok(originalComparison.passed && originalComparison.existingDefinitionsUnchanged && originalComparison.existingRelativeOrderPreserved);
const hashes = JSON.parse(await readFile(path.join(directory, 'protected-file-comparison.json'), 'utf8'));
assert.ok(hashes.unchanged);
const http = JSON.parse(await readFile(path.resolve(directory, '../http/post-results.json'), 'utf8'));
assert.ok(http.passed && http.completedCases === 72 && http.failures.length === 0);
const report = { comparedAt: new Date().toISOString(), passed: true, ruleId: recorded.ruleId, submittedAtUtc: recorded.submittedAtUtc, confirmedAtUtc: recorded.confirmedAtUtc, actualFormMatchesReviewedCandidate: true, threeEnabledRulesOnly: true, newRuleFirst: true, existingIdsAndDefinitionsRetained: true, existingRelativeOrderRetained: true, protectedFilesUnchanged: true, protectedSourceFiles: hashes.sourceCount, liveHttpCasesPassed: http.completedCases, liveHttpFailures: http.failures, rollbackPerformed: false, evidence: ['../cloudflare/post-new-rule.txt','../cloudflare/post-rule-inventory.txt','../cloudflare/post-rules-overview.txt','post-cloudflare-comparison.json','protected-file-comparison.json','../http/post-results.json'], limitation: 'Control-plane review uses root-captured authenticated visible state and recorded rule link ID, not an API version export. HTTP outcomes are from the independent read-only HTTP agent.' };
await writeFile(path.join(directory, 'FINAL-INDEPENDENT-REVIEW.json'), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report));
