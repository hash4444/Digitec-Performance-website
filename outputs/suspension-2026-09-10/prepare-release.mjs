import {readFile,writeFile,copyFile,symlink} from 'node:fs/promises';
import assert from 'node:assert/strict';
import path from 'node:path';
const root=process.cwd();
const checkout=path.join(root,'outputs/suspension-2026-09-10/release-checkout');
const read=p=>readFile(path.join(checkout,p),'utf8');
const save=(p,s)=>writeFile(path.join(checkout,p),s);
for(const file of ['src/pages/SuspensionRepairPage.tsx','src/data/suspensionContent.ts','src/styles/suspension.css','scripts/validate-suspension.mjs']) await copyFile(path.join(root,file),path.join(checkout,file));
let app=await read('src/App.tsx');
app=app.replace('import "./styles/oil-change.css";','import "./styles/oil-change.css";\nimport "./styles/suspension.css";');
app=app.replace('const OilChangePage = lazy(() => import("./pages/OilChangePage"));','const OilChangePage = lazy(() => import("./pages/OilChangePage"));\nconst SuspensionRepairPage = lazy(() => import("./pages/SuspensionRepairPage"));');
app=app.replace('<Route path="/services/oil-change-dubai" element={<OilChangePage />} />','<Route path="/services/oil-change-dubai" element={<OilChangePage />} />\n          <Route path="/services/suspension-repair-dubai" element={<SuspensionRepairPage />} />');
assert.ok(!app.includes('TransmissionPage'));
await save('src/App.tsx',app);
let services=await read('src/data/services.ts');
services=services.replace("metaTitle: 'Suspension Repair Dubai | AIRMATIC, Shocks, Air Struts'","metaTitle: 'Car Suspension Repair Dubai | Air Suspension | DIGI-TEC'").replace("metaDescription: 'Air suspension sagging or harsh ride? Book AIRMATIC, shock and air-strut inspection and repair in Dubai with vehicle-specific parts options.'","metaDescription: 'Clunks, a harsh ride or sagging air suspension? Book a suspension inspection in Al Quoz, Dubai. Vehicle-specific diagnosis and a clear repair quote.'");
await save('src/data/services.ts',services);
const sharedBrand=await readFile(path.join(root,'src/pages/BrandServicePage.tsx'),'utf8');
const block=sharedBrand.match(/      \{!isArabic && combo\.serviceSlug === 'suspension-repair'[\s\S]*?\n      \)\}/)?.[0];
assert.ok(block);
await save('src/pages/BrandServicePage.tsx',(await read('src/pages/BrandServicePage.tsx')).replace('      {/* Models */}',`${block}\n\n      {/* Models */}`));
const sharedManifest=await readFile(path.join(root,'src/lib/route-manifest.ts'),'utf8');
const changedPaths=sharedManifest.match(/const suspensionUpdatedPaths = new Set\([\s\S]*?\n\]\);/)?.[0];
assert.ok(changedPaths);
let manifest=await read('src/lib/route-manifest.ts');
manifest=manifest.replace('export const publicRoutes =',`${changedPaths}\n\nexport const publicRoutes =`).replace('=> oilChangeUpdatedPaths.has(route.path) ?','=> (oilChangeUpdatedPaths.has(route.path) || suspensionUpdatedPaths.has(route.path)) ?');
await save('src/lib/route-manifest.ts',manifest);
const pkg=JSON.parse(await read('package.json'));
pkg.scripts.build+=' && node scripts/validate-suspension.mjs';
await save('package.json',JSON.stringify(pkg,null,2)+'\n');
await symlink(path.join(root,'node_modules'),path.join(checkout,'node_modules'),'junction');
console.log('Prepared suspension-only release source; transmission work remains in the shared checkout.');
