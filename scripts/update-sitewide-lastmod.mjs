import { readFile, writeFile } from 'node:fs/promises';

// Compare primary page content against the saved pre-edit crawl. Shared footer,
// header, schema formatting and script hashes must not refresh every page date.
const directory = 'outputs/sitewide-seo-2026-09-17/audit';
const before = new Map(JSON.parse(await readFile(`${directory}/baseline-local-records.json`, 'utf8')).map(row => [row.path, row]));
const phase = process.argv[2] || 'final';
if (!/^[a-z]+$/.test(phase)) throw new Error('Invalid audit phase');
const after = JSON.parse(await readFile(`${directory}/${phase}-local-records.json`, 'utf8'));
const updated = after.filter(row => {
  const previous = before.get(row.path);
  return !previous || row.contentSha256 !== previous.contentSha256 || row.title !== previous.title ||
    JSON.stringify(row.descriptions) !== JSON.stringify(previous.descriptions) ||
    ['/', '/ar', '/vrx', '/ar/vrx'].includes(row.path); // image, initial visibility and main landmarks
}).map(row => row.path).sort();
await writeFile('src/data/sitewideSeoUpdatedPaths.ts', `// Primary content or metadata changed in the 17 September release.\n// Generated by scripts/update-sitewide-lastmod.mjs from saved before/after HTML.\nexport const sitewideSeoUpdatedPaths = new Set<string>(${JSON.stringify(updated, null, 2)});\n`);
await writeFile('outputs/sitewide-seo-2026-09-17/changed-content-paths.json', JSON.stringify(updated, null, 2));
console.log(`Recorded truthful content modification dates for ${updated.length} routes.`);
