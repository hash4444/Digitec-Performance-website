import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
const root=process.cwd();
const out=path.join(root,'outputs/r11');
const readJson=async file=>JSON.parse(await readFile(path.join(out,file),'utf8'));
const baseline=await readJson('baseline/routes.json');
const after=await readJson('after/routes.json');
const beforeSummary=await readJson('baseline/summary.json');
const afterSummary=await readJson('after/summary.json');
const beforeSources=await readJson('baseline/source-manifest.json');
const afterSources=await readJson('after/source-manifest.json');
const allowed=new Set(await readJson('approved-route-changes.json'));
const sourceAllowed=new Set([...(await readJson('r1-application-files.json')),...(await readJson('extra-application-files.json'))]);
const beforeMap=new Map(baseline.map(row=>[row.path,row]));
const afterMap=new Map(after.map(row=>[row.path,row]));
const sourceBeforeMap=new Map(beforeSources.files.map(row=>[row.path,row.sha256]));
const sourceAfterMap=new Map(afterSources.files.map(row=>[row.path,row.sha256]));
const issues=[];
const check=(valid,kind,details={})=>{if(!valid)issues.push({kind,...details});};
const fields=['title','description','h1','h2','h3','headings','canonical','noindex','hreflang','contentSha256','internalLinks','images','schemaTypes','schema','whatsapp','telephone'];
const changed=[];
for(const row of after){
  const previous=beforeMap.get(row.path);
  check(Boolean(previous),'new-route',{path:row.path});
  if(!previous)continue;
  const changes=fields.filter(key=>JSON.stringify(row[key])!==JSON.stringify(previous[key]));
  if(changes.length)changed.push({path:row.path,fields:changes});
  for(const key of ['canonical','noindex','hreflang'])check(JSON.stringify(row[key])===JSON.stringify(previous[key]),'canonical-indexability-hreflang-change',{path:row.path,key,before:previous[key],after:row[key]});
}
for(const row of baseline)check(afterMap.has(row.path),'removed-route',{path:row.path});
check(after.length===baseline.length,'route-count',{before:baseline.length,after:after.length});
const sitemapPaths=text=>[...text.matchAll(/<loc>([^<]+)<\/loc>/g)].map(match=>match[1]).sort();
check(JSON.stringify(sitemapPaths(await readFile(path.join(out,'baseline/sitemap.xml'),'utf8')))===JSON.stringify(sitemapPaths(await readFile(path.join(out,'after/sitemap.xml'),'utf8'))),'sitemap-canonical-set-change');
check(afterSummary.focusedRouteCount===beforeSummary.focusedRouteCount,'cluster-count-change');
check(afterSummary.brokenInternalLinks.length===0,'broken-focused-links',{rows:afterSummary.brokenInternalLinks});
check(afterSummary.missingFragments.length===0,'missing-focused-fragments',{rows:afterSummary.missingFragments});
const unexpected=changed.filter(row=>!allowed.has(row.path));
check(unexpected.length===0,'unexpected-rendered-changes',{rows:unexpected});
for(const route of allowed)check(afterMap.has(route)&&beforeMap.has(route),'invalid-approved-route',{path:route});
const appSourceChanges=[...new Set([...sourceBeforeMap.keys(),...sourceAfterMap.keys()])].filter(file=>file.startsWith('src/')&&sourceBeforeMap.get(file)!==sourceAfterMap.get(file)).map(file=>({file,before:sourceBeforeMap.get(file),after:sourceAfterMap.get(file)}));
const unexpectedSources=appSourceChanges.filter(row=>!sourceAllowed.has(row.file));
check(unexpectedSources.length===0,'unrelated-application-source-change',{rows:unexpectedSources});
const run=spawnSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8',windowsHide:true});
check(run.status===0&&run.stdout.trim()===beforeSummary.git.head,'head-change',{before:beforeSummary.git.head,after:run.stdout.trim()});
const r1=JSON.parse(await readFile(path.join(out,'validation/summary.json'),'utf8'));
check(r1.passed,'r1-regression-checks-failed',{issues:r1.issues});
const sourceFinal=[];
for(const file of sourceAllowed){const data=await readFile(path.join(root,file));sourceFinal.push({file,sha256:createHash('sha256').update(data).digest('hex')});check(createHash('sha256').update(data).digest('hex')===sourceAfterMap.get(file),'source-changed-after-audit',{file});}
const result={validatedAt:new Date().toISOString(),passed:issues.length===0,publicRoutesBefore:baseline.length,publicRoutesAfter:after.length,sitemapCanonicalsBefore:beforeSummary.sitemapCanonicalCount,sitemapCanonicalsAfter:afterSummary.sitemapCanonicalCount,focusedRoutes:afterSummary.focusedRouteCount,approvedChangedRoutes:allowed.size,actualChangedRoutes:changed.length,changed,unexpected,applicationSourceChanges:appSourceChanges,unexpectedSources,r1RegressionPassed:r1.passed,sourceFinal,issues};
await mkdir(path.join(out,'validation'),{recursive:true});
await writeFile(path.join(out,'validation/r11-summary.json'),JSON.stringify(result,null,2));
console.log(JSON.stringify({...result,sourceFinal:undefined},null,2));
if(!result.passed)process.exitCode=1;
