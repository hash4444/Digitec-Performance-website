export const localizeBlogPostToArabic = (post: BlogPost): BlogPost => {
  const meta = arabicPostMeta[post.slug] ?? {
    title: post.title,
    excerpt: post.excerpt,
    metaTitle: post.metaTitle,
    metaDescription: post.metaDescription,
    topic: 'صيانة السيارة',
  };
  const headings = headingTemplates(meta.topic);
  const paragraphs = paragraphTemplates(meta.topic);
  const lists = listTemplates(meta.topic);
  const questions = faqQuestions(meta.topic);
  const answers = faqAnswers(meta.topic);
  let headingIndex = 0;
  let paragraphIndex = 0;
  let questionIndex = 0;
  let inFaq = false;

  return {
    ...post,
    ...meta,
    author: 'فريق ورشة ديجي-تك',
    readTime: post.readTime.replace(/^(\d+).*$/, '$1 دقائق قراءة'),
    ogTitle: meta.title,
    ogDescription: meta.excerpt,
    twitterTitle: meta.title,
    twitterDescription: meta.excerpt,
    gallery: post.slug === 'best-defender-workshop-dubai'
      ? post.gallery?.map((image, index) => ({ ...image, ...(defenderGalleryArabic[index] ?? {}) }))
      : post.gallery,
    content: post.content.map((block) => {
      if (block.type === 'h2') {
        inFaq = /faq/i.test(block.text ?? '');
        const text = inFaq ? 'الأسئلة الشائعة' : headings[headingIndex++ % (headings.length - 1)];
        return { ...block, text };
      }
      if (block.type === 'h3') {
        const text = inFaq
          ? questions[questionIndex++ % questions.length]
          : headings[(headingIndex + questionIndex++) % (headings.length - 1)];
        return { ...block, text };
      }
      if (block.type === 'ul') {
        return {
          ...block,
          items: (block.items ?? []).map((_, index) => lists[index % lists.length]),
        };
      }
      const text = inFaq
        ? answers[Math.max(0, questionIndex - 1) % answers.length]
        : paragraphs[paragraphIndex++ % paragraphs.length];
      return { ...block, text };
    }),
  };
};

export const localizePostSummaryToArabic = <T extends { slug: string; title: string; excerpt: string }>(post: T): T => {
  const fixed = arabicPostMeta[post.slug];
  if (fixed) return { ...post, title: fixed.title, excerpt: fixed.excerpt };
  const brand = post.title.replace(/^Best /, '').replace(/ Workshop in Dubai.*$/, '').replace(/ Maintenance Guide.*$/, '');
  return {
    ...post,
    title: `دليل أفضل ورشة ${brand} في دبي`,
    excerpt: `دليل عملي لمالكي ${brand} في دبي عن الصيانة والتشخيص والأعطال الشائعة وكيفية اختيار ورشة متخصصة.`,
  };
};

